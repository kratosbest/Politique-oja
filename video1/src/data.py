"""Writes data/montage_data.js for montage.html: words on the edit timeline (scribe on work/edit.mp4),
cut times of the edit (from work/edl.json) and the outline of Benin (from motion/src/bj_map.js)."""
import json, re, pathlib
B = pathlib.Path(__file__).resolve().parent.parent
words = json.load(open(B / 'work/words_edit.json'))
edl = json.load(open(B / 'work/edl.json'))
cuts, t = [], 0.0
for a, b in edl:
    t += b - a; cuts.append(round(t, 3))
src = (B.parent / 'motion/src/bj_map.js').read_text()
ben = re.search(r"BEN:'([^']+)'", src).group(1)
pts = [tuple(map(float, p.split(','))) for p in re.findall(r'(-?\d+\.?\d*,-?\d+\.?\d*)', ben)]
xs, ys = [p[0] for p in pts], [p[1] for p in pts]
box = [min(xs), min(ys), max(xs), max(ys)]
(B / 'data/montage_data.js').write_text(
    '// generated by src/data.py\n'
    f'const WORDS = {json.dumps(words, ensure_ascii=False)};\n'
    f'const CUTS = {json.dumps(cuts[:-1])};\n'
    f'const EDIT_DUR = {t:.3f};\n'
    f"const BENIN = {{ d: '{ben}', box: {json.dumps(box)} }};\n")
print(len(words), 'words', len(cuts), 'segments', round(t, 2), 's', box)
