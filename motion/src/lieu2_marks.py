"""Voice timing for the mascot tutorial « Ajouter un lieu » (oja_ajout_lieu_mascotte.html): one line of
assets/lieu2/voix_ajout_lieu.txt per scene. From the per-character timings of the voice (written by src/tts.py) and the
real silences of the audio, it gives each line's start and end in the voice file, the length of each scene (its line, a
lead-in and a pause after it), and the words of each line in scene seconds (the animations and the subtitles follow them).
Writes assets/lieu2/voix_marks.js (window.VO, read by the page) and assets/lieu2/voix_marks.json (read by src/music41.py).
usage (from motion/): python3 src/lieu2_marks.py"""
import json, re, subprocess
import numpy as np

LEAD = [0.9, .35, .35, .35, .35, .35, .35, .35, .35]       # the line starts this long after its scene starts
TAIL = [.7, 1.4, 1.1, .9, 1.5, 1.4, 1.4, 2.4, 1.0]          # pause after the line (the screen keeps moving)
END = 4.2                                                    # end card after the last line
d = json.load(open('assets/lieu2/voix_ajout_lieu.mp3.json'))
txt = ''.join(d['characters']); S = d['character_start_times_seconds']; E = d['character_end_times_seconds']
lines = [re.sub(r'\[[^\]]*\]\s*', '', l).strip() for l in open('assets/lieu2/voix_ajout_lieu.txt', encoding='utf-8').read().strip().split('\n')]
assert len(lines) == len(LEAD)
SR = 16000
pcm = np.frombuffer(subprocess.run(['ffmpeg', '-v', 'error', '-i', 'assets/lieu2/voix_ajout_lieu.mp3', '-ac', '1', '-ar', str(SR), '-f', 'f32le', '-'],
                                   capture_output=True, check=True).stdout, np.float32)
HOP = .01; db = np.array([20 * np.log10(np.sqrt((pcm[int(t * SR):int((t + .02) * SR)] ** 2).mean()) + 1e-9) for t in np.arange(0, len(pcm) / SR, HOP)])
silent = db < -50
def onset(t, back=.45):
    i = int(t / HOP)
    for k in range(i, max(6, int((t - back) / HOP)), -1):
        if silent[k - 6:k].all(): return round(k * HOP, 3)
    return t
def offset(t, ahead=.45):
    i = int(t / HOP)
    for k in range(i, min(len(silent) - 6, int((t + ahead) / HOP))):
        if silent[k:k + 6].all(): return round(k * HOP, 3)
    return t
out = {'lead': LEAD, 'line': [], 'dur': [], 'words': [], 'text': []}
pos = 0
for i, line in enumerate(lines):
    j = txt.index(line, pos); pos = j + len(line)
    # the end is taken on the last letter: the timing of a closing « ! » or « . » runs into the next line
    k = j + max(i2 for i2, ch in enumerate(line) if ch.isalnum())
    a, b = onset(S[j]), offset(E[k] - .05)
    out['line'].append([a, b]); out['text'].append(line)
    out['dur'].append(round(LEAD[i] + (b - a) + TAIL[i] + (END if i == len(lines) - 1 else 0), 2))
    out['words'].append([[m.group(0), round(S[j + m.start()] - a + LEAD[i], 3), round(E[j + m.end() - 1] - a + LEAD[i], 3)]
                         for m in re.finditer(r"[^\s]+", line)])
out['total'] = round(sum(out['dur']), 2)
json.dump(out, open('assets/lieu2/voix_marks.json', 'w'), ensure_ascii=False)
open('assets/lieu2/voix_marks.js', 'w').write('// generated by src/lieu2_marks.py\nwindow.VO = ' + json.dumps(out, ensure_ascii=False) + ';\n')
for i, (l, du) in enumerate(zip(lines, out['dur'])): print(i, du, out['line'][i], l[:60])
print('total', out['total'])
